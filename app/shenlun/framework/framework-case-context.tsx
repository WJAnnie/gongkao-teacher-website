function findMeta(text: string) {
  return CASES.find((item) => item.match.some((key) => text.includes(key)));
}

function cleanExampleText(card: HTMLElement) {
  const walker = document.createTreeWalker(card, NodeFilter.SHOW_TEXT);
  let node = walker.nextNode();
  while (node) {
    const value = node.nodeValue ?? '';
    node.nodeValue = value
      .replace(/江苏省考\s*[·｜-]?\s*/g, '')
      .replace(/国考\s*[·｜-]?\s*/g, '')
      .replace(/省考\s*[·｜-]?\s*/g, '')
      .replace(/课堂真题整理\s*[·｜-]?\s*/g, '')
      .replace(/课堂答案\s*[·｜-]?\s*/g, '')
      .replace(/真题/g, '例子');
    node = walker.nextNode();
  }
}

function addLine(parent: HTMLElement, className: string, label: string, text: string) {
  const p = document.createElement('p');
  p.className = className;
  const b = document.createElement('b');
  b.textContent = label;
  p.append(b, document.createTextNode(text));
  parent.append(p);
}

function replaceWithTruthCase(card: HTMLElement, meta: CaseMeta) {
  if (card.dataset.truthReplaced === '1') return;

  const copy = card.querySelector<HTMLElement>('.framework-deep-case-copy, .critique-copy')
    ?? (card.firstElementChild as HTMLElement | null);
  if (!copy) return;

  const label = copy.querySelector<HTMLElement>('.framework-voice-example-label, :scope > span');
  const title = copy.querySelector<HTMLElement>('h5');
  if (label) label.textContent = '真题例子 / 从题目到答案';
  if (title) title.textContent = meta.title;

  copy.querySelectorAll<HTMLElement>(':scope > p').forEach((p) => p.remove());
  card.querySelector<HTMLElement>(':scope > aside')?.remove();

  const context = document.createElement('div');
  context.className = 'framework-case-context framework-case-truth';

  const source = document.createElement('p');
  source.className = 'framework-case-source';
  source.textContent = 'TRUE QUESTION / 真题情境';
  context.append(source);
  addLine(context, 'framework-case-task', '题目怎么问：', meta.question);
  addLine(context, 'framework-case-material', '材料里提到：', meta.material);
  addLine(context, 'framework-case-answer', '可以这样写：', meta.answer);
  addLine(context, 'framework-case-teacher', '我会提醒你：', meta.teacher);

  if (title) title.insertAdjacentElement('afterend', context);
  else copy.append(context);

  card.classList.add('framework-truth-case');
  card.dataset.truthReplaced = '1';
}

export function FrameworkCaseContext({ activeLayer }: { activeLayer: string }) {
  useEffect(() => {
    const frame = window.requestAnimationFrame(() => {
      const root = document.getElementById('framework-manual-top');
      if (!root) return;

      const cards = root.querySelectorAll<HTMLElement>('.framework-deep-case, .framework-voice-example, .type-v3-critique');
      cards.forEach((card) => {
        if (card.dataset.truthReplaced === '1') return;
        const originalText = card.innerText;
        const meta = findMeta(originalText);
        cleanExampleText(card);
        if (meta) replaceWithTruthCase(card, meta);
      });
    });

    return () => window.cancelAnimationFrame(frame);
  }, [activeLayer]);

  return null;
}
