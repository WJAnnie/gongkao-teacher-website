function findMeta(text: string) {
  return CASES.find((item) => item.match.some((key) => text.includes(key)));
}

function cleanExampleText(card: HTMLElement) {
  const walker = document.createTreeWalker(card, NodeFilter.SHOW_TEXT);
  let node = walker.nextNode();
  while (node) {
    const value = node.nodeValue ?? '';
    node.nodeValue = value
      .replace(/江苏省考\s*[·｜-]?\s*/g, '')
      .replace(/国考\s*[·｜-]?\s*/g, '')
      .replace(/省考\s*[·｜-]?\s*/g, '')
      .replace(/课堂真题整理\s*[·｜-]?\s*/g, '课堂示例 · ')
      .replace(/真题/g, '例子')
      .replace(/这类例子这类题/g, '这类题');
    node = walker.nextNode();
  }
}

export function FrameworkCaseContext({ activeLayer }: { activeLayer: string }) {
  useEffect(() => {
    const frame = window.requestAnimationFrame(() => {
      const root = document.getElementById('framework-manual-top');
      if (!root) return;

      const cards = root.querySelectorAll<HTMLElement>('.framework-deep-case, .framework-voice-example, .type-v3-critique');
      cards.forEach((card) => {
        cleanExampleText(card);
        card.querySelector('.framework-case-context')?.remove();

        const meta = findMeta(card.innerText);
        if (!meta) return;

        const context = document.createElement('div');
        context.className = 'framework-case-context';
        context.innerHTML = `
          <p class="framework-case-source">举个例子</p>
          <p class="framework-case-task"><b>题目怎么问：</b>${meta.task}</p>
          <p class="framework-case-material"><b>材料里有什么：</b>${meta.material}</p>
          <p class="framework-case-thinking"><b>这时怎么想：</b>${meta.thinking}</p>
        `;

        const copy = card.querySelector<HTMLElement>('.framework-deep-case-copy') ?? card.firstElementChild as HTMLElement | null;
        if (copy) copy.prepend(context);
        else card.prepend(context);
      });
    });

    return () => window.cancelAnimationFrame(frame);
  }, [activeLayer]);

  return null;
}
