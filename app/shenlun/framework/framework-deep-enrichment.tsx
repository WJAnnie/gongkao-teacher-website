import type { ReactNode } from 'react';

function Block({ label, title, children }: { label: string; title: string; children: ReactNode }) {
  return <section className="framework-deep-block"><header><span>{label}</span><h4>{title}</h4></header>{children}</section>;
}
function Talk({ children }: { children: ReactNode }) { return <div className="framework-deep-talk">{children}</div>; }
function Case({ label, title, children, note }: { label: string; title: string; children: ReactNode; note: ReactNode }) {
  return <article className="framework-deep-case"><div className="framework-deep-case-copy"><span>{label}</span><h5>{title}</h5>{children}</div><aside><b>阅 / 这道题看什么</b>{note}</aside></article>;
}
function Compare({ rows }: { rows: Array<[string, string, string]> }) {
  return <table className="framework-deep-table"><tbody>{rows.map(([a,b,c]) => <tr key={`${a}-${b}`}><th>{a}</th><td>{b}</td><td>{c}</td></tr>)}</tbody></table>;
}

