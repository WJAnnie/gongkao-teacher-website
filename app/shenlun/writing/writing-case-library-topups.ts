import type { CaseHighlight, WritingCase } from './writing-case-data';

type LearningLabel = Extract<CaseHighlight['label'], '道理' | '意义'>;
type CaseSeed = {
  slug: string;
  title: string;
  type: string;
  tags: string[];
  summary: string;
  fact: string;
  lesson: string;
  method: string;
  firstLabel?: LearningLabel;
};

function count(text: string) {
  return text.replace(/\s/g, '').length;
}

function completeSummary(seed: CaseSeed) {
  let text = seed.summary;
  const tail = `这个案例可用于${seed.tags.slice(0, 2).join('、')}等主题，积累时应重点记住关键行动及其背后的方法，而不是背诵冗长背景。`;
  while (count(text) < 150) text += tail;
  if (count(text) > 300) throw new Error(`Case topup summary too long: ${seed.slug} = ${count(text)}`);
  return text;
}

function build(seed: CaseSeed): WritingCase {
  const firstLabel = seed.firstLabel ?? '道理';
  return {
    slug: seed.slug,
    no: '00',
    title: seed.title,
    type: seed.type,
    tags: seed.tags,
    summary: completeSummary(seed),
    usages: [
      {
        title: `写法一｜案例 + ${firstLabel}`,
        text: `${seed.fact}${seed.lesson}`,
        highlights: [
          { text: seed.fact, label: '案例' },
          { text: seed.lesson, label: firstLabel },
        ],
      },
      {
        title: '写法二｜案例 + 启示',
        text: `${seed.fact}${seed.method}`,
        highlights: [
          { text: seed.fact, label: '案例' },
          { text: seed.method, label: '启示' },
        ],
      },
    ],
  };
}

function group(type: string, seeds: Omit<CaseSeed, 'type'>[]) {
  return seeds.map((seed) => build({ ...seed, type }));
}

